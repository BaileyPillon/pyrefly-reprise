/** One wave of flame: air roaring through a band, with crackle riding it. */
function flameWave(at: number, dur: number, gain: number, pan: number, seed: number): DesignLayer[] {
  return [
    {
      kind: 'air',
      at,
      dur,
      freq: 300,
      freqTo: 1200,
      q: 0.5,
      attack: 0.035,
      curve: 2.2,
      hold: 0.12,
      gain,
      pan,
      seed,
    },
    ...scatter(8, { at: at + 0.05, span: dur * 0.7, freq: 2400, freqSpread: 0.9, dur: 0.04, gain: 0.08, seed: seed + 11 }),
  ];
}

/** A crack of lightning: the strike, a metallic arc, and the room answering. */
function strike(at: number, gain: number, pan: number, seed: number): DesignLayer[] {
  return [
    {
      kind: 'air',
      at,
      dur: 0.08,
      freq: 4200,
      freqTo: 900,
      q: 0.5,
      attack: 0.0012,
      curve: 8,
      gain,
      pan,
      seed,
    },
    {
      kind: 'ring',
      at: at + 0.004,
      freq: 988,
      ratio: 3.41,
      index: 2.2,
      indexTo: 0.15,
      dur: 0.26,
      curve: 5,
      gain: gain * 0.4,
      pan: -pan,
    },
  ];
}

