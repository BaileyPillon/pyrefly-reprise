/**
 * The upper tiers, and the spells that have no base version.
 *
 * A tier is not the same sound louder. Going up a tier adds a *second gesture*:
 * Fira is two waves of flame where Fire is one, Firaga puts a sub-bass whoomp
 * in front of both and a choir behind them. The pitch material never changes —
 * everything stays inside B minor — so a Firaga and a cursor tick still belong
 * to the same game.
 */

