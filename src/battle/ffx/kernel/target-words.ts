/** What the menu reads of a target word. */
export interface TargetWordSpec {
  /** Bit 0: a target step follows (the resolver answers 0xFE); clear means the command commits at once. */
  step: boolean;
  /** Bit 1: the foe side is shown first. */
  foeFirst: boolean;
  /** Bits 2 and 3: 0 each member alone, 1 grouped by Chr+0x504, 2 all of each side in one candidate, 3 only the user. */
  mode: 0 | 1 | 2 | 3;
  /** Bit 5: the cursor may be switched to the other side. */
  switchable: boolean;
  /** Bit 6: the dead may be chosen (they are added to the candidates; the living stay). */
  canTargetDead: boolean;
}

/** Decode a target word. */
export function decodeTargetWord(word: number): TargetWordSpec {
  return {
    step: (word & 0x1) !== 0,
    foeFirst: (word & 0x2) !== 0,
    mode: ((word >> 2) & 3) as 0 | 1 | 2 | 3,
    switchable: (word & 0x20) !== 0,
    canTargetDead: (word & 0x40) !== 0,
  };
}

/** The decoded target word of a record id, or `undefined` for a record this table does not hold (an enemy's, or one of ours). */
export function targetSpecOf(recordId: number | undefined): TargetWordSpec | undefined {
  const word = recordId === undefined ? undefined : TARGET_WORDS[recordId];
  return word === undefined ? undefined : decodeTargetWord(word);
}
