/**
 * The target and misc words of the game's 68 item rows (re-parity RC9 lane X2-H; **FFX-2 only**): what the Confusion pick reads of an item
 * (`kernel/confusion-pick.ts`). Numbers only, read field by field from the Steam HD build's `battle/kernel/item.bin` (build 25501027, SHA-256
 * of the exe 6EA7F142...CD69); no text and no game code. One row per item id `0x2000 + n`, each `[cursor, misc]`:
 * - `cursor` `Item+0x10`: the target flags (bit 1 enemy side first, bits 2 and 3 the target type, 0x20 the team split / reverse bit, 0x40 can
 *   target the dead, 0x80 can target all, 0x400 far), the same word as a command row's `cursor` (`command-menu-rows.ts`);
 * - `misc` `Item+0x14`: the misc flags; bit 0x20000000 (a Confused girl may pick the command) is set on all 68.
 * Every item row has `Item+0x0d` = 0 (a direct command, no sub-menu) and `Item+0x0e` = 4 (the Item list). Proof: `parity-ffx2-confusion-pick.test.ts`
 * replays the game's own pick over these rows.
 */

