/** The number of item rows. */
export const FFX2_ITEM_ROWS = ITEM_ROW_DATA.length;

/** The game's item id (`0x2000 + n`) of an in-range row, else false. */
export function isItemId(id: number): boolean {
  return (id & 0xffff) >= 0x2000 && (id & 0xffff) < 0x2000 + FFX2_ITEM_ROWS;
}

/** The row of item id `id` (`0x2000 + n`): its target flags and misc flags. */
export function itemRow(id: number): { readonly cursor: number; readonly misc: number } {
  const low = (id & 0xffff) - 0x2000;
  const row = ITEM_ROW_DATA[low];
  if (row === undefined) throw new RangeError(`item row ${id.toString(16)} is outside the ${FFX2_ITEM_ROWS} rows of the item table`);
  return { cursor: row[0], misc: row[1] };
}
