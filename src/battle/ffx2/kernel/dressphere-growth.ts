export const FFX2_JOB_GROWTH: readonly Ffx2JobGrowth[] = RAW.map((r, i) => ({
  id: 0x5000 + i,
  user: r[0] as number,
  attackCommand: r[1] as number,
  hp: [r[2], r[3], r[4]] as unknown as Ffx2JobGrowth['hp'],
  mp: [r[5], r[6], r[7]] as unknown as Ffx2JobGrowth['mp'],
  stats: Array.from({ length: 8 }, (_, k) => r.slice(8 + 5 * k, 13 + 5 * k)) as unknown as Ffx2JobGrowth['stats'],
}));

/** The job record for an id, or `undefined` when the index is 0x22 or more (the game returns no record). */
export function jobGrowth(job: number): Ffx2JobGrowth | undefined {
  const i = job & 0xfff;
  return i < FFX2_JOB_GROWTH.length ? FFX2_JOB_GROWTH[i] : undefined;
}

