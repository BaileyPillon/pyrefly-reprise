/**
 * FFX-2 dressphere growth data: the 34 job records' growth bytes, the level curve of the 23 save records, and the
 * per-girl job map, as read from the Steam build's `battle/kernel/job.bin` (34 rows of 228 bytes, ids 0x5000 to
 * 0x5021), `ply_rom.bin` (23 rows of 8 bytes) and the table at VA 0x00d48288 of FFX-2.exe (build 25501027,
 * SHA-256 6EA7F142...CD69).  Numbers only; the rules that use them are in `dressphere-stats.ts`.
 *
 * **Game case: FFX-2 only.** Spec: `research/re-ffx2-dressphere.md` section 1.
 */

/** One dressphere's record, the part the stat builder reads. */
export interface Ffx2JobGrowth {
  /** Job id, `0x5000 + row`. */
  readonly id: number;
  /** Who wears it: 255 anyone, 0 Yuna, 1 Rikku, 2 Paine (byte `+0x08`). */
  readonly user: number;
  /** The command the Attack slot runs, and the one Berserk and the counter-attack abilities run (u16 `+0x0c`). */
  readonly attackCommand: number;
  /** HP growth bytes `+0x0e`: [a, d, c]; HP = a*L - L*L*10/d + c. */
  readonly hp: readonly [number, number, number];
  /** MP growth bytes `+0x11`: [a, d, c]; MP = a*L/10 - L*L/d + c. */
  readonly mp: readonly [number, number, number];
  /**
   * The eight 5-byte rows from `+0x14`, in file order: strength, vitality (the game's Defense), magic, spirit (Magic
   * Defense), dexterity (Agility), avoid (Evasion), hit (Accuracy), luck.  Each row is [a, d1, c, d2, d3]:
   * stat = L/d1 - (L*L/16)/d2/d3 + a*L/10 + c.
   */
  readonly stats: readonly (readonly [number, number, number, number, number])[];
}

