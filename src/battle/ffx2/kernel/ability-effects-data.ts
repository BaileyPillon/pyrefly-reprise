/**
 * FFX-2 auto-ability rows, effect half: the element, status, auto-status and cast-speed fields of the 162 rows of
 * `battle/kernel/a_ability.bin` (176 bytes each), keeping only rows that have any.  Numbers only, no text.  The stat and
 * ability-word half is in `dressphere-rows.ts`.
 *
 * **Game case: FFX-2 only.** Source: the Steam build's `a_ability.bin` (build 25501027).  Spec:
 * `research/re-ffx2-dressphere.md` section 4.
 */

/** One status entry: [status index 0..23, value]. */
export type Ffx2StatusEntry = readonly [number, number];

/** The effect fields of one auto-ability row. */
export interface Ffx2AbilityEffects {
  /** Row `special_data` bit 0: the statuses apply only while HP is in danger (the SOS abilities). */
  readonly sos: boolean;
  /** Element bit masks (bit 0 Fire, 1 Ice, 2 Thunder, 3 Water, 4 Gravity, 5 Holy): weapon element (+0x15), absorb (+0x16), null (+0x17), half (+0x18), weak (+0x19). */
  readonly elements: readonly [number, number, number, number, number];
  /** Cast-speed entry (+0x10 command or menu id, +0x12 signed percent); 0 when none. */
  readonly castType: number;
  readonly castPercent: number;
  /** Statuses the ability keeps on the character (group 1 mask at +0x84, group 2 at +0x88) and their turn counts (+0x8c, 24 signed bytes). */
  readonly auto1: number;
  readonly auto2: number;
  /** The chance the weapon adds a group-1 status (+0x24) and a group-2 status (+0x3c, signed). */
  readonly touch1: readonly Ffx2StatusEntry[];
  readonly touch2: readonly Ffx2StatusEntry[];
  /** The ward against a group-1 (+0x54) and group-2 (+0x6c) status: 255 is immunity. */
  readonly ward1: readonly Ffx2StatusEntry[];
  readonly ward2: readonly Ffx2StatusEntry[];
  /** The turn counts for the auto statuses (+0x8c). */
  readonly times: readonly Ffx2StatusEntry[];
}

