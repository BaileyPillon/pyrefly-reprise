const ABILITY_TABLE: readonly Ffx2AbilityRow[] = ABILITY_AP.map((ap, i) => {
  const s = ABILITY_SPARSE.find((r) => r[0] === i);
  return s
    ? { special: s[1] as number, words: [s[2], s[3], s[4]] as unknown as Ffx2AbilityRow['words'], ap, up: s.slice(5) as unknown as Ffx2UpStatus }
    : { special: 0, words: [0, 0, 0], ap, up: ZERO10 };
});

/**
 * An auto-ability row by id.  The game's table lookup answers an index outside the file's range with the first row, so
 * 0x80a2 and above read as 0x8000.
 */
export function abilityRow(id: number): Ffx2AbilityRow {
  const i = id & 0xfff;
  return (i < ABILITY_TABLE.length ? ABILITY_TABLE[i] : ABILITY_TABLE[0]) as Ffx2AbilityRow;
}

