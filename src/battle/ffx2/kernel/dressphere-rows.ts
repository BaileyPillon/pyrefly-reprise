/**
 * FFX-2 equipment and ability rows the stat builder reads: auto-ability rows (`a_ability.bin`, 162 rows of 176 bytes,
 * ids 0x8000 to 0x80a1), accessories (`accessory.bin`, 128 rows of 84 bytes, ids 0x9000 to 0x907f), garment grids
 * (`plate.bin`, 64 rows of 128 bytes, ids 0x6000 to 0x603f) and each dressphere's ability list (`job.bin` bytes
 * `+0x3c` to `+0x7b`), from the Steam build's `battle/kernel` files (build 25501027).  Numbers only, no text.
 *
 * **Game case: FFX-2 only.** Spec: `research/re-ffx2-dressphere.md` sections 1 and 4.
 */

/** The ten signed bytes of an `up_status` array: HP %, MP %, then flat Strength, Defense, Magic, Magic Defense, Agility, Accuracy, Evasion, Luck. */
export type Ffx2UpStatus = readonly [number, number, number, number, number, number, number, number, number, number];

/** What the stat builder and the battle code read from one auto-ability row. */
export interface Ffx2AbilityRow {
  /** Row `special_data` (`+0x14`): bit 0 only acts at low HP, bit 1 usable ability, bit 2 stackable (may appear twice in a list), bit 3 not for player-side monsters. */
  readonly special: number;
  /** The three auto-ability words OR-ed into `Chr+0x650`, `+0x652`, `+0x654` (u16 at `+0xa4`, `+0xa6`, `+0xa8`). */
  readonly words: readonly [number, number, number];
  /** AP needed to master it (u16 `+0xae`). */
  readonly ap: number;
  /** `up_status` (`+0x1a`). */
  readonly up: Ffx2UpStatus;
}

