/** The game id of one of our abilities, if it is on a ladder. */
export function gameIdOf(abilityId: string): number | undefined {
  return ABILITY_GAME_ID[abilityId];
}

const REVERSE = new Map<number, string>();
const AMBIGUOUS = new Set<number>();
for (const [id, game] of Object.entries(ABILITY_GAME_ID)) {
  if (REVERSE.has(game)) AMBIGUOUS.add(game);
  else REVERSE.set(game, id);
}
/** Several dresspheres share a game command (every Attack, Libra): those have no single ability of ours. */
export function abilityOfGameId(game: number): string | undefined {
  return AMBIGUOUS.has(game) ? undefined : REVERSE.get(game);
}
