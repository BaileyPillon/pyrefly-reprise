function rng(seed) { let a = seed >>> 0; return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
function motes() {
  const r = rng(20260921); let s = '';
  for (let i = 0; i < 90; i++) { // dust lives inside the shafts (src/scenes/zanarkand-dome.ts, decision 3)
    const y = r() * 760, x = 330 + r() * 330 + (y / 760) * (r() - 0.6) * 220;
    s += `<circle cx="${x.toFixed(0)}" cy="${y.toFixed(0)}" r="${(0.8 + r() * 1.8).toFixed(1)}" fill="rgba(255,244,220,${(0.35 + r() * 0.55).toFixed(2)})"/>`;
  }
  const cols = ['190,255,210', '255,255,255', '255,190,225']; // pyreflies: green / white / pink (docs/ENGINE-API.md "Particles")
  for (let i = 0; i < 34; i++) {
    const x = r() * 1440, y = 120 + r() * 640, c = cols[i % 3], rad = 2 + r() * 3;
    s += `<circle cx="${x.toFixed(0)}" cy="${y.toFixed(0)}" r="${(rad * 2.6).toFixed(1)}" fill="rgba(${c},0.10)"/><circle cx="${x.toFixed(0)}" cy="${y.toFixed(0)}" r="${rad.toFixed(1)}" fill="rgba(${c},0.85)"/>`;
  }
  return `<svg class="motes" viewBox="0 0 1440 810">${s}</svg>`;
}
function sparks() {
  const r = rng(954); let s = '';
  for (let i = 0; i < 22; i++) { const a = r() * Math.PI * 2, d0 = 40 + r() * 50, d1 = d0 + 30 + r() * 110; const cx = 905, cy = 330;
    s += `<line x1="${(cx + Math.cos(a) * d0).toFixed(0)}" y1="${(cy + Math.sin(a) * d0).toFixed(0)}" x2="${(cx + Math.cos(a) * d1).toFixed(0)}" y2="${(cy + Math.sin(a) * d1).toFixed(0)}" stroke="rgba(255,236,190,${(0.5 + r() * 0.5).toFixed(2)})" stroke-width="${(1.5 + r() * 2.5).toFixed(1)}" stroke-linecap="round"/>`; }
  return s;
}

