#!/usr/bin/env node
/**
 * gen-pro-shots.mjs [path to shots.json] : writes `src/data/procam/proShots.ts`, the compact shot table `?camera=pro` plays (conference demo, lane "pro-camera", 2026-10-23).
 *
 *   node tools/procam/gen-pro-shots.mjs D:/Tools/pyrefly-scratch/2026-10-22/real-motion/final/shots.json
 *
 * The input is the real-motion lane's camera table (`final/shots.json`, format echoes-real-camera-shots/2): the camera programs of the retail game read out of its own scripts and replayed
 * against six PS2 recordings (Bailey's 2026-10-18 rule allows retail data; this file holds numbers only). Each shot is already laid on our Gagazet stage (metres, Y up) by that lane, in two
 * forms: FREE and CLAMPED (the eye held within 35 degrees of the painted plate's front). This generator keeps the CLAMPED eye (the plate and the billboards cannot be seen from behind), the real
 * look-at, lens and roll, and the real ease of each key; a trapezoid ease becomes a cosine. For each shot it keeps the DESIGN pair (the actor's and the target's feet and the actor's height the
 * numbers were laid for), so the engine can re-register the shot onto the figures where they really stand (`engine/procam/ProTrack.ts`, `registerKeys`).
 *
 * Only the shots Chapter I (FFX, Seymour Flux) can play are kept: the caster close shot (spells, items), the black-magic landings, Seymour's start and launch shots, the killing blow, the
 * victory close-ups and the skill start. Chapter IV (FFX-2) has no shot table: its auto camera is a rule (`engine/procam/ProFollower.ts`), and only its constants and its ranked candidates are
 * copied here.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ?? 'D:/Tools/pyrefly-scratch/2026-10-22/real-motion/final/shots.json';
const out = resolve(here, '../../src/data/procam/proShots.ts');
const j = JSON.parse(readFileSync(src, 'utf8'));

const r3 = (n) => Math.round(n * 1000) / 1000;
const v3 = (a) => a.map(r3);
const EASE = { cut: 0, linear: 1, cosine: 2 };

/** The shot groups kept: a group is the variant id without its trailing `#n`. */
const KEEP = [
  /^ffx\.cast\.start\.(tidus|yuna|kimahri)(\.ally)?#/,
  /^ffx\.cast\.launch\.(fire|thunder|demi)\.(tidus|lulu)#/,
  /^ffx\.enemy\.start\.(protect|flare|total-annihilation|full-life)\./,
  /^ffx\.enemy\.launch\.(total-annihilation|cross-cleave|flare|banish|full-life|break|bio|demi|slowga|drain)#/,
  /^ffx\.attack\.(tidus|yuna|kimahri)\.finisher#/,
  /^ffx\.victory\.(tidus|yuna|kimahri)#/,
  /^ffx\.skill\.start\.(tidus|kimahri)#/,
];

const groups = {};
for (const t of j.shotTypes) {
  for (const v of t.variants ?? []) {
    if (!KEEP.some((re) => re.test(v.id))) continue;
    const g = v.stage?.gagazet;
    if (!g || !g.rigs || g.rigs.length < 2 || !(v.seconds > 0)) continue;
    if ((g.plateCoverageMin?.clamped ?? 0) < 0.6) continue; // the lane's own measure: less than 60 percent of the frame on painting (the two big launches: 0.11 to 0.48) -> the engine plays an authored stand-in
    const group = v.id.replace(/#\d+$/, '').replace(/^ffx\./, '');
    const keys = g.rigs.map((r, i) => {
      const c = g.clamped?.[i];
      const e = v.keysFFX?.[i]?.ease;
      const ease = typeof e === 'string' ? (EASE[e] ?? 2) : 2;
      return [Math.round(r.tSec * 1000), ...v3(c?.position ?? r.position), ...v3(r.lookAt), r3(r.fov), r3(r.rollDeg ?? 0), ease];
    });
    (groups[group] ??= []).push({
      id: v.id.replace(/^ffx\./, ''),
      ms: Math.round(v.seconds * 1000),
      weight: r3(v.weight ?? 1),
      status: v.status,
      design: { A: v3(g.anchorOurs), T: v3(g.targetOurs), H: r3(g.anchorHeightOurs), mirror: g.mirror === true, scope: g.scope },
      keys,
    });
  }
}

const auto = j.ffx2AutoCamera;
const autoOut = {
  focus: v3(auto.focusOurs),
  homeAzimuthDeg: r3(auto.homeAzimuthDeg),
  lensDeg: r3(auto.params.lens0 ? 2 * Math.atan(240 / auto.params.lens0) * (180 / Math.PI) : 32.18),
  follower: { focusGain: auto.params.follower.focusGain, angGain: auto.params.follower.angGain, angCapDeg: auto.params.follower.angCapDeg, radGain: auto.params.follower.radGain },
  idle: auto.params.idle,
  cands: auto.rankedClamped.map((c) => ({ eye: v3(c.eye), azDeg: r3(c.azFromHomeDeg), elDeg: r3(c.elevAboveAimDeg), fitM: r3(c.fitM) })),
};

const lines = [];
lines.push(`/**
 * GENERATED by \`node tools/procam/gen-pro-shots.mjs <shots.json>\` -- do not edit. The real FFX camera shots of Chapter I laid on our Gagazet stage, and the FFX-2 auto camera's
 * constants (conference demo, lane "pro-camera"). Source: the real-motion lane's \`final/shots.json\` (retail camera programs read out of the game's own scripts, replayed against six PS2
 * recordings; status per shot: PROVEN or DECODED, \`status\`). Game case: the shots are FFX only (Chapter I); the auto-camera block is FFX-2 only (Chapter IV).
 *
 * A key is [t ms, eye x y z, look x y z, fov deg, roll deg, ease] with ease 0 = cut (hold the last key until this one), 1 = linear, 2 = cosine (a trapezoid ease is read as a cosine).
 * The eye is the CLAMPED one (within 35 degrees of the painted plate's front). \`design\` is the pair the numbers were laid for: the actor's feet A, the target's feet T, the actor's height H.
 */
import type { ProShotRow, ProAutoCamera } from '../../engine/procam/ProTypes.ts';
`);
lines.push('export const PRO_SHOTS: Readonly<Record<string, readonly ProShotRow[]>> = {');
for (const [name, rows] of Object.entries(groups)) {
  lines.push(`  ${JSON.stringify(name)}: [`);
  for (const r of rows) lines.push(`    ${JSON.stringify(r)},`);
  lines.push('  ],');
}
lines.push('};');
lines.push('');
lines.push(`/** The FFX-2 auto camera (Chapter IV): its decoded constants and its ranked, plate-clamped candidates on the Bevelle stage. */\nexport const PRO_AUTO_CAMERA: ProAutoCamera = ${JSON.stringify(autoOut)};`);
lines.push('');
writeFileSync(out, lines.join('\n'));
const n = Object.values(groups).reduce((a, r) => a + r.length, 0);
console.log(`wrote ${out}: ${Object.keys(groups).length} groups, ${n} shots, ${lines.length} lines`);
