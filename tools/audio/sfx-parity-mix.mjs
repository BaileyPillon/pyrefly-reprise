#!/usr/bin/env node
/**
 * SFX parity, the mix (decision 52i, proposal P1): write `src/audio/sfxV2/parityTrims.ts`.
 *
 *   node tools/audio/sfx-parity-mix.mjs            write the table
 *   node tools/audio/sfx-parity-mix.mjs --check    exit 1 when the file on disk is not what the inputs give
 *
 * Inputs: `docs/audio/sfx-parity-mix.json` (one row per event: the retail-ratio level, whether the D-210 floor
 * applies, the cap) and `public/audio/manifest.json` (each v2 cue's mastered level and true peak). To move the floor
 * or the cap, edit the JSON header and rerun; nothing else changes. The derivation is `parityDerive.ts`, the same
 * module the unit test uses. Game case: both (each game gets its own trims).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { deriveTrims } from '../../src/audio/sfxV2/parityDerive.ts';

const ROOT = new URL('../../', import.meta.url);
const OUT = new URL('src/audio/sfxV2/parityTrims.ts', ROOT);
const mix = JSON.parse(readFileSync(new URL('docs/audio/sfx-parity-mix.json', ROOT), 'utf8'));
const manifest = JSON.parse(readFileSync(new URL('public/audio/manifest.json', ROOT), 'utf8'));
const trims = deriveTrims(mix, manifest.sfxV2.cues);

const fmt = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const block = (game) => {
  const lines = Object.entries(trims[game]).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `    '${k}': ${fmt(v)},`);
  return `  ${game}: {\n${lines.join('\n')}\n  },`;
};
const text = `/**
 * GENERATED by \`node tools/audio/sfx-parity-mix.mjs\` from \`docs/audio/sfx-parity-mix.json\` and the manifest's v2 cue levels.
 * Do not edit by hand; \`tests/unit/audio-sfx-parity-mix.test.ts\` fails when this is not what the inputs give.
 *
 * The P1 mix (decision 52i): the trim in dB each (game, cue) takes at play time, so the event sits at its retail-ratio
 * level (floor under the party's hits, ceiling ${mix.capLufs} LUFS). A cue that is absent plays at its mastered level: HOLD rows
 * (52j), cues no row names, and everything the first bank plays. Game case: both, each game its own.
 */

export const PARITY_TRIMS_DB: Readonly<Record<'ffx' | 'ffx2', Readonly<Record<string, number>>>> = {
${block('ffx')}
${block('ffx2')}
};
`;

if (process.argv.includes('--check')) {
  const now = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  if (now !== text) {
    console.error('sfx-parity-mix: src/audio/sfxV2/parityTrims.ts is stale; run node tools/audio/sfx-parity-mix.mjs');
    process.exit(1);
  }
  console.log('sfx-parity-mix: parityTrims.ts is current');
} else {
  writeFileSync(OUT, text);
  console.log(`sfx-parity-mix: wrote ${Object.keys(trims.ffx).length} FFX and ${Object.keys(trims.ffx2).length} FFX-2 trims`);
}
