#!/usr/bin/env node
/**
 * SFX parity, the final repack of the v2 sprite (spec 5.1 item 5): which stand-ins a recorded original has made
 * unnecessary, and the file that tells `sfx-v2-sprite.py --exclude` to leave them out.
 *
 *   node tools/audio/sfx-parity-repack.mjs                                      report the plan
 *   node tools/audio/sfx-parity-repack.mjs --write [--exclude-out <file.json>]  write src/audio/sfxV2/retired.ts (and the exclude list)
 *   node tools/audio/sfx-parity-repack.mjs --check                              exit 1 when retired.ts is not what the plan gives
 *
 * It starts itself again with `--experimental-transform-types` because the plan plays the scripted fight (every ability of both games through
 * the real presenter and chapter voice; `tests/unit/helpers/sfxFight.ts`) to learn every way the game reaches a stand-in.
 * A cue retires only when each of those ways ends at a recorded original in the game's core pack (`tools/audio/sfx-parity-retire.mjs`
 * says why it is that strict). With no pack shipped it retires nothing, and `--write` then writes the empty list.
 *
 * After `--write`: run `python tools/audio/sfx-v2-sprite.py --work <dir> --exclude <the file> --install`, then
 * `node tools/audio/sfx-parity-mix.mjs` (the trims are derived from the sprite's cues), then `node tools/audio/qa.mjs --only=sfx`.
 * The audio-sfx-v2 test keeps "V2_CUES is the sprite plus the retired list" true at every step.
 *
 * Game case: both; every decision is per game.
 */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

// The scripted fight loads the game's data modules, which need type transforms: run again with them if started without.
if (!process.execArgv.includes('--experimental-transform-types')) {
  const r = spawnSync(process.execPath, ['--experimental-transform-types', '--no-warnings', ...process.argv.slice(1)], { stdio: 'inherit' });
  process.exit(r.status ?? 1);
}

const { planRetirement, retiredBytes } = await import('./sfx-parity-retire.mjs');
const { V2_CUES } = await import('../../src/audio/sfxV2/cues.ts');

const ROOT = new URL('../../', import.meta.url);
const OUT = new URL('src/audio/sfxV2/retired.ts', ROOT);
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const value = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const manifest = JSON.parse(readFileSync(new URL('public/audio/manifest.json', ROOT), 'utf8'));
const sprite = new Set(Object.keys(manifest.sfxV2?.cues ?? {}));
// The cues already retired are in V2_CUES but not in the sprite: the plan covers what the sprite holds now.
const packs = manifest.sfxParity?.packs ?? {};

const { scenarios, playScenario } = await import('../../tests/unit/helpers/sfxFight.ts');
const uses = { ffx: [], ffx2: [] };
for (const game of ['ffx', 'ffx2']) {
  const seen = new Set();
  for (const scenario of scenarios(game)) {
    for (const cue of await playScenario(game, scenario)) {
      if (!cue.key.startsWith('v2:')) continue;
      const id = `${cue.key}|${cue.events === undefined ? '-' : cue.events.join(',')}`;
      if (seen.has(id)) continue;
      seen.add(id);
      uses[game].push({ key: cue.key, events: cue.events });
    }
  }
}

const plan = planRetirement({
  sprite,
  cues: V2_CUES,
  core: { ffx: packs['ffx-core']?.cues, ffx2: packs['ffx2-core']?.cues },
  uses,
});

const fmt = (list) => `[${list.map((n) => `'${n}'`).join(', ')}]`;
const text = `/**
 * GENERATED by \`node tools/audio/sfx-parity-repack.mjs --write\`. Do not edit by hand;
 * \`tests/unit/audio-sfx-parity-repack.test.ts\` fails when this is not what the plan gives.
 *
 * The v2 cues the final repack took out of the sprite because a recorded original in the game's core pack replaces every
 * use of them (\`retire.ts\`). They stay in \`V2_CUES\` (the voice still asks for them by name, and the mixer finds the
 * original); until the pack has decoded, the first-bank stand-in plays, so nothing is ever silent. Empty until a core
 * pack ships.
 */

export const RETIRED_V2_CUES: readonly string[] = ${plan.retired.length === 0 ? '[]' : fmt(plan.retired)};
`;

if (flag('--check')) {
  const now = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
  if (now !== text) {
    console.error('sfx-parity-repack: src/audio/sfxV2/retired.ts is stale; run node tools/audio/sfx-parity-repack.mjs --write');
    process.exit(1);
  }
  console.log('sfx-parity-repack: retired.ts is current');
} else {
  const saved = manifest.sfxV2 ? retiredBytes(plan, manifest.sfxV2.cues, manifest.sfxV2.bytes ?? 0, manifest.sfxV2.duration ?? 0) : 0;
  console.log(`v2 sprite: ${sprite.size} cues, ${((manifest.sfxV2?.bytes ?? 0) / 1e6).toFixed(2)} MB`);
  console.log(`core packs shipped: ${['ffx-core', 'ffx2-core'].filter((p) => packs[p]).join(', ') || 'none'}`);
  console.log(`retire ${plan.retired.length}: ${plan.retired.join(', ') || '(nothing)'}  -> gives back about ${(saved / 1e6).toFixed(2)} MB`);
  const reasons = {};
  for (const [name, why] of Object.entries(plan.kept)) (reasons[why.replace(/^(ffx2?) /, '$1 ').replace(/\(.*\)/, '').trim()] ??= []).push(name);
  for (const [why, names] of Object.entries(reasons)) console.log(`keep ${names.length} (${why}): ${names.slice(0, 12).join(', ')}${names.length > 12 ? ', ...' : ''}`);
  if (flag('--write')) {
    writeFileSync(OUT, text);
    const exclude = value('--exclude-out');
    if (exclude) writeFileSync(exclude, `${JSON.stringify({ exclude: plan.retired }, null, 1)}\n`);
    console.log(`wrote src/audio/sfxV2/retired.ts${exclude ? ` and ${exclude}` : ''}`);
  }
}
