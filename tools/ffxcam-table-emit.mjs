/**
 * **Writing the shot table as TypeScript** (FFX only; `tools/ffxcam-table-build.mjs` uses it): `evrae-shots.ts` holds the routes, rows, views and the header; the shots themselves go to
 * `evrae-shots-1.ts`, `-2.ts`... so that no source file passes the house 400 lines (a shot is one line). Deterministic: the same table is the same text.
 *
 * Game case: FFX only.
 */

const MAX_LINES = 360;

const num = (v) => (Number.isInteger(v) ? String(v) : String(Math.round(v * 1000) / 1000));
const vec = (v) => `[${v.map(num).join(',')}]`;
const shape = (s) => (Array.isArray(s) ? `[${s.map(num).join(',')}]` : String(s));
const key = (k) => `[${num(k[0])},${vec(k[1])},${vec(k[2])},${num(k[3])},${num(k[4])},${shape(k[5])}]`;
const shotLine = (id, d) => `  ${id}: { kind: '${d.kind}', len: ${d.len}, keys: [${d.keys.map(key).join(',')}] },`;
const branches = (bs) => `[${bs.map(([s, w]) => `['${s}', ${w}]`).join(', ')}]`;
const quoted = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`);

export const TABLE_HEADER = `/**
 * **The Evrae fight's shot table** (FFX only; the hidden Fayth chapter's website camera, \`../../../engine/ffxcam/tableDirector.ts\`).
 *
 * Derived by replaying FFX's battle-camera programs for the Evrae fight from Bailey's own copy, simplified to keyframes and clamped (variant B); not the game's scripts.
 *
 * It holds numbers only: poses and the curves between them (\`./shotTypes.ts\`), keyed by the beat, the ability, the acting slot, the target, the airship's range and the branch the programs drew.
 * No instruction, no condition, no script: \`tests/unit/ffxcam-table-data.test.ts\` pins that. How it was made, and what is a fit, is \`research/ffx-battle-camera-evrae.md\`.
 *
 * - Written by \`tools/ffxcam-table-build.mjs\` from a recording (\`tools/ffxcam-record.mjs\`) on Bailey's PC; do not edit by hand.
 * - Variant B: every pose was clamped to an eye azimuth within 35 degrees of the near default view's and to the look direction's pitch band the painted sky plate covers (\`../../../engine/ffxcam/variant.ts\`).
 * - Fitted within {{pos}} FFX units (eye and look-at), {{deg}} degrees (roll, field of view, view direction) of the clamped path; branch weights are how many of {{samples}} seeds of the camera's dice drew the branch.
 */
`;

/** The files of the table: `[{ name, text }]`. `meta` is `{ samples, tolerance }`. */
export function emitTable(table, meta) {
  const files = [];
  const ids = Object.keys(table.shots).sort();
  const chunks = [];
  for (let i = 0; i < ids.length; i += MAX_LINES) chunks.push(ids.slice(i, i + MAX_LINES));
  chunks.forEach((chunk, n) => {
    const body = chunk.map((id) => shotLine(id, table.shots[id])).join('\n');
    files.push({
      name: `evrae-shots-${n + 1}.ts`,
      text: `/** Shots ${chunk[0]} to ${chunk[chunk.length - 1]} of the Evrae fight's table (\`./evrae-shots.ts\`): generated by \`tools/ffxcam-table-build.mjs\`, numbers only. */\nimport type { ShotDef } from './shotTypes.ts';\n\nexport const EVRAE_SHOTS_${n + 1}: Readonly<Record<string, ShotDef>> = {\n${body}\n};\n`,
    });
  });
  const routes = Object.entries(table.routes)
    .map(([id, cells]) => `  ${id}: {\n${Object.entries(cells).map(([c, bs]) => `    ${quoted(c)}: ${branches(bs)},`).join('\n')}\n  },`)
    .join('\n');
  const rows = Object.entries(table.rows)
    .map(([row, r]) => `  ${quoted(row)}: { ${[r.open ? `open: '${r.open}'` : '', r.launch ? `launch: '${r.launch}'` : ''].filter(Boolean).join(', ')} },`)
    .join('\n');
  const defeat = Object.entries(table.defeat).map(([k, bs]) => `    ${quoted(k)}: ${branches(bs)},`).join('\n');
  const imports = chunks.map((_, n) => `import { EVRAE_SHOTS_${n + 1} } from './evrae-shots-${n + 1}.ts';`).join('\n');
  const spread = chunks.map((_, n) => `  ...EVRAE_SHOTS_${n + 1},`).join('\n');
  const header = TABLE_HEADER.replace('{{pos}}', String(meta.tolerance.pos)).replace('{{deg}}', String(meta.tolerance.deg)).replace('{{samples}}', String(meta.samples));
  files.unshift({
    name: 'evrae-shots.ts',
    text: `${header}\n${imports}\nimport type { EvraeShotTable } from './shotTypes.ts';\n\nexport const EVRAE_SHOTS: EvraeShotTable = {\n  format: 'echoes-evrae-shots/1',\n  shots: {\n${spread}\n  },\n  routes: {\n${routes}\n  },\n  rows: {\n${rows}\n  },\n  views: { near: '${table.views.near}', far: '${table.views.far}' },\n  scenes: { pullBack: ${branches(table.scenes.pullBack)}, moveIn: ${branches(table.scenes.moveIn)} },\n  victory: { n: ${branches(table.victory.n)}, f: ${branches(table.victory.f)} },\n  defeat: {\n${defeat}\n  },\n};\n`,
  });
  return files;
}
