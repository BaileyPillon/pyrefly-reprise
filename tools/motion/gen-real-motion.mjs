#!/usr/bin/env node
/**
 * gen-real-motion.mjs [path to motion-from-game.json] : writes `src/data/motion/realMotion.ts`, the compact table `?curves=real` reads (conference demo, integration 2, 2026-10-22).
 *
 *   node tools/motion/gen-real-motion.mjs D:/Tools/pyrefly-scratch/2026-10-22/real-motion/final/motion-from-game.json
 *
 * The input is the real-motion lane's table (numbers read from the retail game's own clip banks and scripts; Bailey's 2026-10-18 rule allows retail data). Only the fields the engine reads are kept:
 * for each party member and boss of Chapter I (FFX) and Chapter IV (FFX-2), the melee/ranged ATTACK chain (real phases, the same phases scaled to Bailey's 1.1 s pick, the lift profiles, the
 * recorded run-in path for Tidus), the first CAST, the light/heavy HIT, the KO and the victory pose. Nothing is invented here: a missing field stays missing and the reader falls back to the
 * `?curves=new` numbers.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ?? 'D:/Tools/pyrefly-scratch/2026-10-22/real-motion/final/motion-from-game.json';
const out = resolve(here, '../../src/data/motion/realMotion.ts');
const j = JSON.parse(readFileSync(src, 'utf8'));

const r1 = (n) => (typeof n === 'number' && Number.isFinite(n) ? Math.round(n * 10) / 10 : undefined);
const r3 = (n) => (typeof n === 'number' && Number.isFinite(n) ? Math.round(n * 1000) / 1000 : undefined);
const arr = (a) => (Array.isArray(a) && a.length ? a.map(r3) : undefined);
const clean = (o) => Object.fromEntries(Object.entries(o).filter(([, v]) => v !== undefined));
const first = (actions, names) => names.map((n) => actions[n]).find(Boolean);

function phases(p) {
  if (!p) return undefined;
  return { windupMs: r1(p.windupMs), travelMs: r1(p.travelMs), holdMs: r1(p.holdMs), returnMs: r1(p.returnMs), settleMs: r1(p.settleMs) };
}

function attack(a) {
  if (!a?.real || !a.demo?.strikeProfile) return undefined;
  const sp = a.demo.strikeProfile;
  const lift = a.real.lift ?? {};
  return clean({
    status: a.status,
    real: phases(a.real),
    snappy: phases(sp),
    arc: r3(sp.arc),
    arcApex: r3(sp.arcApex),
    returnArc: r3(sp.returnArc),
    bias: r3(sp.bias),
    approachProfile: arr(lift.approachProfile11),
    returnProfile: arr(lift.returnProfile11),
    xApproach: arr(a.recording?.cumulativeDistanceProfile11RunIn),
    xReturn: arr(a.recording?.cumulativeDistanceProfile11Return),
  });
}

function cast(a) {
  if (!a?.real) return undefined;
  return clean({ status: a.status, windupMs: r1(a.real.windupMs), hitOffsetMs: r1(a.real.releaseHitOffsetMs), returnMs: r1(a.real.returnMs), liftShare: r3(a.real.lift?.maxShare) });
}

function hit(a) {
  if (!a?.real) return undefined;
  return clean({ status: a.status, totalMs: r1(a.real.totalMs), peakMs: r1(a.real.peakMs), recoveryEndMs: r1(a.real.recoveryEndMs) });
}

function ko(a) {
  if (!a?.real) return undefined;
  return clean({ status: a.status, fallMs: r1(a.real.fallMs), floorImpactMs: r1(a.real.floorImpactMs) });
}

/** The victory pose: how long the body takes to crouch and spring to 90 percent of its lift (the painting is a still; the rest of the real pose is a hold). */
function victory(a) {
  if (!a?.real) return undefined;
  const p = a.real.profile11;
  const pose = a.real.poseMs;
  let crouchMs;
  let riseMs;
  if (Array.isArray(p) && p.length > 2 && typeof pose === 'number') {
    const max = Math.max(...p);
    const low = p.indexOf(Math.min(...p.slice(0, Math.ceil(p.length / 2))));
    const up = p.findIndex((v) => v >= 0.9 * max);
    const step = pose / (p.length - 1);
    crouchMs = r1(Math.max(0, low) * step);
    riseMs = r1(Math.max(up, 1) * step);
  }
  return clean({ status: a.status, poseMs: r1(pose), liftMaxShare: r3(a.real.liftMaxShare), crouchMs, riseMs });
}

const ATTACK = ['attack.runIn', 'attack.throw', 'attack.lance', 'attack'];
const CAST = ['cast', 'cast.white', 'cast.black', 'cast.magic1', 'cast.darkness'];
const HIT = ['hit.light', 'hit.heavy'];

const table = {};
for (const game of ['ffx', 'ffx2']) {
  table[game] = {};
  for (const [key, ch] of Object.entries(j.games[game].characters)) {
    const act = ch.actions ?? {};
    const row = clean({
      attack: attack(first(act, ATTACK)),
      cast: cast(first(act, CAST)),
      hit: hit(first(act, HIT)),
      ko: ko(act.ko),
      victory: victory(act.victory),
    });
    if (Object.keys(row).length) table[game][key] = row;
  }
}

const header = `/**
 * THE REAL GAME'S BATTLE MOTION, as numbers (conference demo, integration 2, 2026-10-22). GENERATED by \`tools/motion/gen-real-motion.mjs\` from the real-motion lane's
 * \`motion-from-game.json\` (clip lengths and event frames read from the retail game's own banks and scripts at 30 fps; Bailey's rule of 2026-10-18 allows retail data). Do not edit by hand:
 * run the tool again. \`status\` is the lane's word for each record (PROVEN: a clip length or event read from the bank; DECODED: measured on the decoded animation; INFERRED: a rule of ours).
 *
 * Game cases (AGENTS.md rule 14): \`ffx\` is FFX only (Chapter I, Seymour Flux); \`ffx2\` is FFX-2 only (Chapter IV, Bahamut). Nothing here is shared between the games.
 *
 * Read by \`src/engine/motion/RealMotion.ts\` only, and only with \`?curves=real\` or \`?curves=real-snappy\`.
 */

export interface RealPhases {
  windupMs: number;
  travelMs: number;
  holdMs: number;
  returnMs: number;
  settleMs: number;
}

export interface RealAttackRow {
  status: string;
  /** The real clips' phases, ms at 30 fps. */
  real: RealPhases;
  /** The same phases scaled so the move totals Bailey's 1.1 s (real proportions kept). */
  snappy: RealPhases;
  /** Peak lift of the approach (windup plus travel) and of the way home, shares of the figure's height; where the approach's apex falls (0..1); the travel's peak-speed bias. */
  arc: number;
  arcApex: number;
  returnArc: number;
  bias: number;
  /** The hip's height over the approach and over the way home at eleven equal steps, shares of height (negative: crouched). */
  approachProfile?: number[];
  returnProfile?: number[];
  /** Tidus only (a PS2 recording of the real run): the share of the run-in's distance covered, at eleven equal steps of the approach and of the way home. */
  xApproach?: number[];
  xReturn?: number[];
}

export interface RealCastRow {
  status: string;
  windupMs?: number;
  hitOffsetMs?: number;
  returnMs?: number;
  liftShare?: number;
}

export interface RealHitRow {
  status: string;
  totalMs?: number;
  peakMs?: number;
  recoveryEndMs?: number;
}

export interface RealKoRow {
  status: string;
  fallMs?: number;
  floorImpactMs?: number;
}

export interface RealVictoryRow {
  status: string;
  poseMs?: number;
  liftMaxShare?: number;
  crouchMs?: number;
  riseMs?: number;
}

export interface RealRow {
  attack?: RealAttackRow;
  cast?: RealCastRow;
  hit?: RealHitRow;
  ko?: RealKoRow;
  victory?: RealVictoryRow;
}

export type RealGame = 'ffx' | 'ffx2';

`;

/** Compact TypeScript literal: arrays on one line, a small flat object on one line, anything bigger one key per line. */
function fmt(v, ind = 0) {
  const pad = ' '.repeat(ind);
  const val = (x, i) => (typeof x === 'string' ? `'${x}'` : fmt(x, i));
  if (Array.isArray(v)) return `[${v.join(', ')}]`;
  if (v && typeof v === 'object') {
    const keys = Object.keys(v);
    const flat = keys.every((k) => typeof v[k] !== 'object' || Array.isArray(v[k]));
    const one = `{ ${keys.map((k) => `${k}: ${val(v[k], 0)}`).join(', ')} }`;
    if (flat && one.length < 150) return one;
    return `{\n${keys.map((k) => `${pad}  ${k}: ${val(v[k], ind + 2)},`).join('\n')}\n${pad}}`;
  }
  return String(v);
}

const body = `export const REAL_MOTION: Readonly<Record<RealGame, Readonly<Record<string, RealRow>>>> = ${fmt(table)};\n`;

writeFileSync(out, header + body, 'utf8');
console.log(`wrote ${out}: ${Object.entries(table).map(([g, t]) => `${g} ${Object.keys(t).join(',')}`).join(' | ')}`);
