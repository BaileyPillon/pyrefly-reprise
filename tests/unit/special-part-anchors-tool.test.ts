/**
 * Test 5 of the FFX-2 Special look (step C1; game case: FFX-2 only: the three Special dresspheres exist only in FFX-2): `tools/special-part-anchors.mjs` and the table it writes,
 * `src/data/art/specialParts.ts`.
 *
 * The test SPAWNS the tool (`tsconfig.json` has no `allowJs`, so importing the `.mjs` would need a declaration file). It reads the committed quarter-size mask fixtures under
 * `tests/fixtures/specials/masks/` and needs no python and no `public/art`: a clean checkout runs it.
 */
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterAll, describe, expect, it } from 'vitest';
import { FIT_ROWS, SPECIAL_PARTS, STAND_POINT } from '../../src/data/art/specialParts.ts';

const ROOT = resolve(__dirname, '..', '..');
const TOOL = resolve(ROOT, 'tools', 'special-part-anchors.mjs');
const FIXTURES = resolve(ROOT, 'tests', 'fixtures', 'specials', 'masks');
const SPECIALS = ['floral-fallal', 'machina-maw', 'full-throttle'] as const;
const POSES = ['idle', 'attack', 'cast', 'hurt'] as const;
const temps: string[] = [];

function run(...args: string[]): { status: number | null; stdout: string; stderr: string } {
  const r = spawnSync(process.execPath, [TOOL, ...args], { cwd: ROOT, encoding: 'utf8' });
  return { status: r.status, stdout: r.stdout, stderr: r.stderr };
}

/** A scratch folder under the temp directory, removed after the run. */
function scratch(): string {
  const dir = mkdtempSync(join(tmpdir(), 'special-masks-'));
  temps.push(dir);
  return dir;
}

/** Copies the fixtures for the given (special, pose) pairs into a scratch masks folder. */
function copyFixtures(dst: string, keep: (special: string, pose: string) => boolean, skipFile?: (special: string, pose: string, file: string) => boolean): void {
  for (const special of SPECIALS) {
    for (const pose of POSES) {
      if (!keep(special, pose)) continue;
      mkdirSync(join(dst, special, pose), { recursive: true });
      for (const f of readdirSync(join(FIXTURES, special, pose))) {
        if (skipFile?.(special, pose, f)) continue;
        copyFileSync(join(FIXTURES, special, pose, f), join(dst, special, pose, f));
      }
    }
  }
}

afterAll(() => {
  for (const dir of temps) rmSync(dir, { recursive: true, force: true });
});

describe('the committed table equals a fresh run on the committed fixtures', () => {
  it('--check exits 0, byte for byte', () => {
    const r = run('--check');
    expect(r.stderr).toBe('');
    expect(r.status).toBe(0);
  });

  it('two runs write the same file, and it is the committed file', () => {
    const dir = scratch();
    expect(run('--out', join(dir, 'a.ts')).status).toBe(0);
    expect(run('--out', join(dir, 'b.ts')).status).toBe(0);
    const a = readFileSync(join(dir, 'a.ts'), 'utf8');
    expect(a).toBe(readFileSync(join(dir, 'b.ts'), 'utf8'));
    expect(a).toBe(readFileSync(resolve(ROOT, 'src', 'data', 'art', 'specialParts.ts'), 'utf8').replace(/\r\n/g, '\n'));
    expect(a.startsWith('// Generated by tools/special-part-anchors.mjs; do not edit by hand')).toBe(true);
  });

  it('--check exits 1 when the committed file is stale', () => {
    const dir = scratch();
    expect(run('--out', join(dir, 'x.ts')).status).toBe(0);
    const fewer = scratch();
    copyFixtures(fewer, (_s, pose) => pose === 'idle' || pose === 'hurt');
    const r = run('--masks', fewer, '--out', join(dir, 'x.ts'), '--check');
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('stale');
  });
});

describe('the rows', () => {
  it('has the four preflight poses for each of the three Specials, and the fixtures hold 4 masks and a meta file for each', () => {
    for (const special of SPECIALS) {
      expect(Object.keys(SPECIAL_PARTS[special].poses).sort(), special).toEqual([...POSES].sort());
      for (const pose of POSES) expect(readdirSync(join(FIXTURES, special, pose)).sort(), `${special}/${pose}`).toEqual(['left.png', 'main.png', 'meta.json', 'right.png', 'whole.png']);
    }
    expect(SPECIAL_PARTS['floral-fallal'].artId).toBe('yuna-floral-fallal');
    expect(SPECIAL_PARTS['machina-maw'].artId).toBe('rikku-machina-maw');
    expect(SPECIAL_PARTS['full-throttle'].artId).toBe('paine-full-throttle');
    for (const special of SPECIALS) expect(SPECIAL_PARTS[special].provisional, special).toBe(true); // the masks are the render fixtures
  });

  it('right and left come from the file name, never from x: Full Throttle\'s attack has the right wing on the screen-right, Floral Fallal\'s idle on the screen-left', () => {
    const ft = SPECIAL_PARTS['full-throttle'].poses['attack']!;
    expect(ft.right.px[0]).toBeGreaterThan(ft.left.px[0]);
    const ff = SPECIAL_PARTS['floral-fallal'].poses['idle']!;
    expect(ff.right.px[0]).toBeLessThan(ff.left.px[0]);
    // the table is per pose: the same part sits in different places in different poses, and the rows are never sorted by x
    const ftIdle = SPECIAL_PARTS['full-throttle'].poses['idle']!;
    expect(ftIdle.right.px[0]).toBeLessThan(ftIdle.left.px[0]);
  });

  it('swapping the two file names swaps the rows (the tool reads names, not positions)', () => {
    const dir = scratch();
    copyFixtures(dir, (s, p) => s === 'floral-fallal' && p === 'idle');
    const swapped = scratch();
    copyFixtures(swapped, () => false);
    mkdirSync(join(swapped, 'floral-fallal', 'idle'), { recursive: true });
    for (const [from, to] of [['left.png', 'right.png'], ['right.png', 'left.png'], ['main.png', 'main.png'], ['whole.png', 'whole.png'], ['meta.json', 'meta.json']] as const) {
      copyFileSync(join(dir, 'floral-fallal', 'idle', from), join(swapped, 'floral-fallal', 'idle', to));
    }
    // the other two Specials are needed for a run to succeed (idle is required for each)
    copyFixtures(swapped, (s, p) => s !== 'floral-fallal' && p === 'idle');
    const out = join(scratch(), 'swapped.ts');
    expect(run('--masks', swapped, '--out', out).status).toBe(0);
    const text = readFileSync(out, 'utf8');
    const idle = /'floral-fallal': \{[\s\S]*?idle: \{\n\s+left: \{ crop: \[[^\]]*\], px: \[(\d+)/.exec(text);
    const ff = SPECIAL_PARTS['floral-fallal'].poses['idle']!;
    expect(Number(idle![1])).toBe(ff.right.px[0]); // the "left" row of the swapped run is the old right part
  });

  it('every crop lies inside the painting and is the square tile the plate wants, every ring radius is capped by the figure\'s width', () => {
    for (const special of SPECIALS) {
      for (const [pose, rows] of Object.entries(SPECIAL_PARTS[special].poses)) {
        const { paint, whole } = rows;
        const wholeW = whole.box[2] - whole.box[0];
        for (const part of [rows.right, rows.left]) {
          const [x0, y0, x1, y1] = part.crop;
          for (const v of part.crop) {
            expect(v, `${special}/${pose}`).toBeGreaterThanOrEqual(0);
            expect(v, `${special}/${pose}`).toBeLessThanOrEqual(1);
          }
          expect(x1).toBeGreaterThan(x0);
          expect(y1).toBeGreaterThan(y0);
          expect(Math.abs((x1 - x0) * paint.width - (y1 - y0) * paint.height), `${special}/${pose} is square in painting px`).toBeLessThan(3);
          expect(part.radiusPx, `${special}/${pose}`).toBeGreaterThan(0);
          expect(part.radiusPx, `${special}/${pose}`).toBeLessThanOrEqual(Math.round(0.35 * wholeW));
          // the part's centre is inside the figure's box
          expect(part.px[0]).toBeGreaterThanOrEqual(whole.box[0]);
          expect(part.px[0]).toBeLessThanOrEqual(whole.box[2]);
          expect(part.px[1]).toBeGreaterThanOrEqual(whole.box[1]);
          expect(part.px[1]).toBeLessThanOrEqual(whole.box[3]);
        }
        // the number point is over the figure's upper middle
        expect(whole.numberPoint[0]).toBe(Math.round((whole.box[0] + whole.box[2]) / 2));
        expect(whole.numberPoint[1]).toBeGreaterThan(whole.box[1]);
        expect(whole.numberPoint[1]).toBeLessThan(whole.box[1] + 0.5 * (whole.box[3] - whole.box[1]));
        expect(paint.baselineY).toBeGreaterThan(paint.contentTop);
      }
    }
  });

  it('a pose with no masks gets no row, and idle is required', () => {
    const dir = scratch();
    copyFixtures(dir, (_s, pose) => pose === 'idle' || (pose === 'hurt' && _s !== 'machina-maw'));
    const out = join(scratch(), 'partial.ts');
    const r = run('--masks', dir, '--out', out);
    expect(r.status).toBe(0);
    expect(r.stderr).toContain('machina-maw/attack');
    expect(r.stderr).toContain('machina-maw/hurt');
    expect(r.stderr).not.toContain('floral-fallal/hurt');
    const text = readFileSync(out, 'utf8');
    expect(text).not.toMatch(/\battack: \{/);
    const noIdle = scratch();
    copyFixtures(noIdle, (_s, pose) => pose !== 'idle');
    const bad = run('--masks', noIdle, '--out', join(scratch(), 'bad.ts'));
    expect(bad.status).toBe(2);
    expect(bad.stderr).toContain('idle is required');
  });

  it('a mask folder without meta.json is read at the masks\' own size (the painting is then the mask)', () => {
    const dir = scratch();
    copyFixtures(dir, (_s, pose) => pose === 'idle', (_s, _p, f) => f === 'meta.json');
    const out = join(scratch(), 'nometa.ts');
    expect(run('--masks', dir, '--out', out).status).toBe(0);
    expect(readFileSync(out, 'utf8')).toContain('height: 384, width: 384');
  });

  it('the tool needs no python and the table needs no art on disk', () => {
    const source = readFileSync(TOOL, 'utf8');
    expect(source).not.toMatch(/child_process|execSync|spawn|\.py\b/); // it runs no other program: sharp decodes the masks
    expect(existsSync(FIXTURES)).toBe(true);
  });
});

/** The text of one Special's block in a generated table, then one pose's `paint` and `whole.box` out of it. */
function poseOf(text: string, special: string, pose: string): { paint: { baselineY: number; contentTop: number; height: number; width: number }; box: number[] } {
  const block = new RegExp(`'${special}': \\{[\\s\\S]*?\\n  \\},`).exec(text)![0];
  const row = new RegExp(`\\n      ${pose}: \\{[\\s\\S]*?\\n      \\},`).exec(block)![0];
  const p = /paint: \{ baselineY: (\d+), contentTop: (\d+), height: (\d+), width: (\d+) \}/.exec(row)!;
  const b = /box: \[(\d+), (\d+), (\d+), (\d+)\]/.exec(row)!;
  return { paint: { baselineY: +p[1]!, contentTop: +p[2]!, height: +p[3]!, width: +p[4]! }, box: [+b[1]!, +b[2]!, +b[3]!, +b[4]!] };
}

describe('--sidecars (the command the handoff tells stage 2 to run)', () => {
  /** A sidecars folder: Machina Maw has all four poses (one of them with a contentTop), Floral Fallal only idle, Full Throttle all four, and one file with no size at all. */
  function sidecars(): string {
    const dir = scratch();
    const put = (art: string, pose: string, body: object): void => {
      mkdirSync(join(dir, art), { recursive: true });
      writeFileSync(join(dir, art, `${pose}.json`), JSON.stringify(body));
    };
    for (const pose of POSES) put('rikku-machina-maw', pose, pose === 'cast' ? { width: 800, height: 1000, baselineY: 950, contentTop: 100 } : { width: 800, height: 1000, baselineY: 950 });
    for (const pose of POSES) put('paine-full-throttle', pose, { width: 800, height: 1000, baselineY: 950 });
    put('yuna-floral-fallal', 'idle', { width: 800, height: 1000, baselineY: 950 });
    put('yuna-floral-fallal', 'hurt', { baselineY: 5 }); // no size: says nothing about the painting, so it is not a match
    return dir;
  }

  function generated(): { text: string; stderr: string } {
    const out = join(scratch(), 'sidecars.ts');
    const r = run('--sidecars', sidecars(), '--out', out);
    expect(r.status).toBe(0);
    return { text: readFileSync(out, 'utf8'), stderr: r.stderr };
  }

  it('a row measured against a sidecar is wholly in the sidecar\'s scale: the top is the figure\'s box, never meta.json\'s render-scale value', () => {
    const { text } = generated();
    const idle = poseOf(text, 'floral-fallal', 'idle');
    expect(idle.paint).toMatchObject({ baselineY: 950, height: 1000, width: 800 });
    expect(idle.paint.contentTop).toBe(idle.box[1]); // the sidecar has no contentTop: the box top in the same 800x1000 scale (it was 196, the 1536 render's row, before)
    expect(idle.paint.contentTop).toBeLessThan(idle.paint.baselineY);
    expect(idle.box[3]).toBeLessThanOrEqual(1000);
    const maw = poseOf(text, 'machina-maw', 'attack');
    expect(maw.paint.contentTop).toBe(maw.box[1]);
    expect(poseOf(text, 'machina-maw', 'cast').paint.contentTop).toBe(100); // a sidecar that has one is believed
  });

  it('a pose with no sidecar, or one without a size, keeps the render-scale rows and is named on stderr', () => {
    const { text, stderr } = generated();
    for (const pose of ['attack', 'cast', 'hurt']) expect(poseOf(text, 'floral-fallal', pose).paint, pose).toMatchObject({ height: 1536, width: 1536 });
    expect(stderr).toContain('floral-fallal/attack');
    expect(stderr).toContain('floral-fallal/hurt');
    expect(stderr).not.toContain('machina-maw');
  });

  it('provisional is cleared per Special, and only when every one of its poses matched a sidecar (Full Throttle stays provisional: its width is with the swords)', () => {
    const { text } = generated();
    const flag = (id: string): string => new RegExp(`'${id}': \\{\\s+artId: '[^']+', silhouetteGirls: [\\d.]+, widthOverHeight: [\\d.]+, provisional: (true|false),`).exec(text)![1]!;
    expect(flag('machina-maw')).toBe('false');
    expect(flag('floral-fallal')).toBe('true'); // one pose of four matched
    expect(flag('full-throttle')).toBe('true');
  });

  it('an empty sidecars folder changes nothing: every Special stays provisional with the fixtures\' rows', () => {
    const out = join(scratch(), 'empty.ts');
    const r = run('--sidecars', scratch(), '--out', out);
    expect(r.status).toBe(0);
    const text = readFileSync(out, 'utf8');
    for (const id of SPECIALS) expect(text, id).toMatch(new RegExp(`'${id}': \\{\\s+artId: '[^']+', silhouetteGirls: [\\d.]+, widthOverHeight: [\\d.]+, provisional: true,`));
    expect(text.replace(/\r\n/g, '\n')).toBe(readFileSync(resolve(ROOT, 'src', 'data', 'art', 'specialParts.ts'), 'utf8').replace(/\r\n/g, '\n'));
  });
});

